def screen_text(text: str) -> Concern | None:
    for concern, phrases in LEXICON.items():
        if any(contains_phrase(text, phrase) for phrase in phrases):
            return concern
    return None


def is_injection(text: str) -> bool:
    return MARKUP.search(text) is not None or any(contains_phrase(text, p) for p in INJECTION_PHRASES)


def is_on_topic(text: str, lesson_terms: frozenset[str]) -> bool:
    folded = fold(text)
    if any(contains_phrase(folded, term) for term in lesson_terms if term):
        return True
    return any(contains_phrase(folded, cue) for cue in LEARNING_CUES)
